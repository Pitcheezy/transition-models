 await seek(sec(data.observations[8].publication_seconds_exact)+.05);
 check('post_release_output_not_ready',(await page.locator('#active').textContent()).includes('범위 밖') && (await page.locator('#ready').textContent()).includes('만족한 발행 관측 없음'));
